def written(path, text):
    """`text` written as a laid file is: UTF-8, its lines ended LF."""
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


LAW_MODULES = ('poise', 'stride', 'modal', 'impedance', 'latent', 'support', 'wrench')


def _ast_verified():
    """Verify the branchless ASTs of the pure control modules and return their source digest."""
    branches = (ast.If, ast.IfExp, ast.While, ast.Match, ast.Try, ast.BoolOp, ast.ClassDef, ast.Lambda, ast.With)
    digest = hashlib.sha1()
    here = os.path.dirname(__file__)
    for p in (__file__, os.path.join(here, 'build.py'), os.path.join(here, 'manifest.py')):
        with open(p, 'rb') as f:
            digest.update(f.read())
    host_dir = os.path.join(REPO, 'host', 'machine')
    for name in LAW_MODULES:
        path = os.path.join(host_dir, name + '.py')
        with open(path, 'rb') as f:
            raw = f.read()
        digest.update(raw)
        if name in ('poise', 'stride', 'impedance', 'latent', 'support'):
            tree = ast.parse(raw.decode('utf-8'))
            bad = [type(n).__name__ for n in ast.walk(tree) if isinstance(n, branches)]
            if bad:
                raise RuntimeError('%s.py has branches: %s' % (name, ', '.join(bad)))
    return digest.hexdigest()[:12]


def _c_header():
    """C11 header and the module constants latent.step, support.couple and wrench._rounds take."""
    from machine import latent, modal, support, wrench
    gamma = ', '.join('%.17g' % float(v) for v in support.GAMMA.ravel())
    pi_mat = ', '.join('%.17g' % float(v) for v in support.PI.ravel())
    return '''/* Generated by tools.cores.transpile_law from machine/{latent,support,wrench}.py */
#include <math.h>
#include <string.h>

#define C_TAU 6.28318530717958647692

static const double G = %.17g, EDGE_S = %.17g, TAU_V = %.17g, ESO_0 = %.17g, ESO_S = %.17g;
static const double SIGMA = %.17g, BLEED = %.17g, ROOM_0 = %.17g, ROOM_1 = %.17g, YAW_M = %.17g;
static const double W_PIN = %.17g, RIDGE = %.17g;
static const double C_GAMMA[21] = {%s};
static const double C_PI_MAT[231] = {%s};

static inline double c_clip(double x, double lo, double hi) { return (x < lo) ? lo : ((x > hi) ? hi : x); }
''' % (modal.G, latent.EDGE_S, support.TAU_V, support.ESO_0, support.ESO_S, support.SIGMA, support.BLEED,
       float(wrench.ROOM[0]), float(wrench.ROOM[1]), wrench.YAW_M, wrench.W_PIN, wrench.RIDGE, gamma, pi_mat)


def _c_latent_support():
    """C11 implementation of `latent.step` and `support.couple`."""
    return '''
void law_latent_step(double *st, const double *tab, int n_tab, double now, double dt, double *out) {
  double hit_vals[59], hit_said[59], hit_sum = 0.0, hit_lerp = 0.0;
  memset(hit_vals, 0, sizeof(hit_vals));
  memset(hit_said, 0, sizeof(hit_said));
  for (int r = 0; r < n_tab; r++) {
    const double *row = tab + r * 120;
    const double at = row[118];
    if ((at <= now + EDGE_S) && (at > now - dt + EDGE_S)) {
      hit_sum += 1.0; hit_lerp += row[119];
      for (int j = 0; j < 59; j++) { hit_vals[j] += row[j]; hit_said[j] += row[59 + j]; }
    }
  }
  const double came = fmin(hit_sum, 1.0);
  for (int j = 0; j < 59; j++) {
    st[118 + j] += fmin(hit_said[j], 1.0) * (hit_vals[j] - st[118 + j]);
    st[59 + j] += came * (st[j] - st[59 + j]);
  }
  st[177] += came * (now - st[177]);
  st[178] += came * (hit_lerp - st[178]);
  const double span = fmax(st[178], dt), u = c_clip((now - st[177] + dt) / span, 0.0, 1.0);
  for (int j = 0; j < 59; j++) st[j] = st[59 + j] + (st[118 + j] - st[59 + j]) * u;
  const double turns = C_TAU * st[56];
  double th = fmod(st[179] + turns * dt, C_TAU);
  if (th < 0.0) th += C_TAU;
  st[179] = th;
  const double u_lt = (u < 1.0) ? 1.0 : 0.0;
  for (int i = 0; i < 11; i++) {
    const double psi = th + st[44 + i], sway = st[55] * st[33 + i], s = sin(psi), c = cos(psi);
    out[0 + i] = st[0 + i] + sway * s;
    out[11 + i] = (st[118 + i] - st[59 + i]) / span * u_lt + sway * turns * c;
    out[22 + i] = -sway * turns * turns * s;
    out[33 + i] = st[11 + i]; out[44 + i] = st[22 + i]; out[55 + i] = psi; out[66 + i] = sway;
  }
  out[77] = turns; out[78] = st[57]; out[79] = st[58];
}

void law_support_couple(const double *q, const double *qd, const double *ref_q,
                        const double *ref_v, double *eso_z, double *out, double *dq) {
  const double s2 = SIGMA * SIGMA, z0 = ESO_S * ESO_S, s4 = s2 * s2, sz4 = z0 * z0, s8 = s4 * s4;
  double phi[21];
  for (int j = 0; j < 21; j++) {
    const double err = q[j] - ref_q[j], e2 = err * err, zm = fmax(eso_z[j] * copysign(1.0, err) - ESO_0, 0.0);
    const double z2 = zm * zm, e4 = e2 * e2, z4 = z2 * z2, e8 = e4 * e4;
    phi[j] = (z4 / (z4 + sz4)) * (e8 / (e8 + s8)) * (err + TAU_V * (qd[j] - ref_v[j]) * e2 / (e2 + s2));
    eso_z[j] /= 1.0 + BLEED * C_GAMMA[j] * (phi[j] * phi[j]);
    dq[j] = C_GAMMA[j] * phi[j];
  }
  for (int i = 0; i < 11; i++) {
    double s = 0.0;
    for (int j = 0; j < 21; j++) s += C_PI_MAT[i * 21 + j] * phi[j];
    out[i] += s;
  }
}
'''


@functools.lru_cache(maxsize=None)
def transpile_law():
    """Verify the control modules' ASTs, emit `build/hosttest/law_core_*.c`, and return its path."""
    os.makedirs(OUT, exist_ok=True)
    digest = _ast_verified()
    c_path = os.path.join(OUT, 'law_core_%s.c' % digest)
    if not os.path.exists(c_path):
        written(c_path, _c_header() + _c_latent_support() + c_wrench_rounds())
    return c_path


@functools.lru_cache(maxsize=None)
def law_library():
    """The compiled C law core (`law_latent_step`, `law_support_couple`, `law_wrench_rounds`); her
    ask is `tools.cores.imp`'s."""
    c_path = transpile_law()
    lib_path, _ = cached([c_path], [], 'law_core', ('-O2',))
    lib = ctypes.CDLL(lib_path)
    dp = ctypes.POINTER(ctypes.c_double)
    lib.law_latent_step.argtypes = [dp, dp, ctypes.c_int, ctypes.c_double, ctypes.c_double, dp]
    lib.law_latent_step.restype = None
    lib.law_support_couple.argtypes = [dp, dp, dp, dp, dp, dp, dp]
    lib.law_support_couple.restype = None
    lib.law_wrench_rounds.argtypes = [dp, dp, ctypes.c_double, ctypes.c_double,
                                      dp, dp, dp, ctypes.c_double, ctypes.c_double,
                                      dp, dp, dp, dp, dp, ctypes.c_double, dp, dp]
    lib.law_wrench_rounds.restype = None
    return lib


def wrench_rounds_c(H0, g0, lo, hi, geo, stride):
    """Run `wrench._rounds` in C (`law_wrench_rounds`) for the 21-unknown contact-free case."""
    import numpy as np
    _nu, _k3, _moment, part, up, lift, mass, grounded, stance, frames, edges, mu = geo
    strides, kinetic = stride
    dp = ctypes.POINTER(ctypes.c_double)
    ptr = lambda a: np.ascontiguousarray(a, dtype=np.float64).ctypes.data_as(dp)
    out = np.empty(21, dtype=np.float64)
    kc = kinetic if kinetic is not None else H0
    law_library().law_wrench_rounds(ptr(H0), ptr(g0), float(lo), float(hi), ptr(part), ptr(up), ptr(lift),
                                    float(mass), float(grounded), ptr(stance), ptr(frames[0]), ptr(frames[1]),
                                    ptr(edges), ptr(mu), float(strides), ptr(kc), out.ctypes.data_as(dp))
    return out
