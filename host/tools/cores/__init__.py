def _c_latent_support():
    """C11 implementation of `latent.step` and `support.couple`."""
    return '''
void law_latent_step(double *st, const double *tab, int n_tab, double now, double dt, double *out) {
  double hit_vals[59], hit_said[59], hit_sum = 0.0, hit_lerp = 0.0;
  memset(hit_vals, 0, sizeof(hit_vals));
  memset(hit_said, 0, sizeof(hit_said));
  for (int r = 0; r < n_tab; r++) {
    const double *row = tab + r * 120;
    const double at = row[118];
    if ((at <= now + EDGE_S) && (at > now - dt + EDGE_S)) {
      hit_sum += 1.0; hit_lerp += row[119];
      for (int j = 0; j < 59; j++) { hit_vals[j] += row[j]; hit_said[j] += row[59 + j]; }
    }
  }
  const double came = fmin(hit_sum, 1.0);
  for (int j = 0; j < 59; j++) {
    st[118 + j] += fmin(hit_said[j], 1.0) * (hit_vals[j] - st[118 + j]);
    st[59 + j] += came * (st[j] - st[59 + j]);
  }
  st[177] += came * (now - st[177]);
  st[178] += came * (hit_lerp - st[178]);
  const double span = fmax(st[178], dt), u = c_clip((now - st[177] + dt) / span, 0.0, 1.0);
  for (int j = 0; j < 59; j++) st[j] = st[59 + j] + (st[118 + j] - st[59 + j]) * u;
  const double turns = C_TAU * st[56];
  double th = fmod(st[179] + turns * dt, C_TAU);
  if (th < 0.0) th += C_TAU;
  st[179] = th;
  const double u_lt = (u < 1.0) ? 1.0 : 0.0;
  for (int i = 0; i < 11; i++) {
    const double psi = th + st[44 + i], sway = st[55] * st[33 + i], s = sin(psi), c = cos(psi);
    out[0 + i] = st[0 + i] + sway * s;
    out[11 + i] = (st[118 + i] - st[59 + i]) / span * u_lt + sway * turns * c;
    out[22 + i] = -sway * turns * turns * s;
    out[33 + i] = st[11 + i]; out[44 + i] = st[22 + i]; out[55 + i] = psi; out[66 + i] = sway;
  }
  out[77] = turns; out[78] = st[57]; out[79] = st[58];
}

void law_support_couple(const double *q, const double *qd, const double *ref_q,
                        const double *ref_v, double *eso_z, double *out, double *dq) {
  const double s2 = SIGMA * SIGMA, z0 = ESO_S * ESO_S, s4 = s2 * s2, sz4 = z0 * z0, s8 = s4 * s4;
  double phi[21];
  for (int j = 0; j < 21; j++) {
    const double err = q[j] - ref_q[j], e2 = err * err, zm = fmax(eso_z[j] * copysign(1.0, err) - ESO_0, 0.0);
    const double z2 = zm * zm, e4 = e2 * e2, z4 = z2 * z2, e8 = e4 * e4;
    phi[j] = (z4 / (z4 + sz4)) * (e8 / (e8 + s8)) * (err + TAU_V * (qd[j] - ref_v[j]) * e2 / (e2 + s2));
    eso_z[j] /= 1.0 + BLEED * C_GAMMA[j] * (phi[j] * phi[j]);
    dq[j] = C_GAMMA[j] * phi[j];
  }
  for (int i = 0; i < 11; i++) {
    double s = 0.0;
    for (int j = 0; j < 21; j++) s += C_PI_MAT[i * 21 + j] * phi[j];
    out[i] += s;
  }
}
'''


def _c_poise_stride():
    """C11 helpers for `poise`, `stride`, and `modal.reading`."""
    return '''
static void c_boxes(const double flat[2][2], const double edge[2], const double tilt[2],
                    double low[2][2], double high[2][2]) {
  for (int k = 0; k < 2; k++) {
    const double oe0 = edge[k], mid0 = flat[k][0] + oe0 * HALF_M * cos(tilt[k]), mid1 = flat[k][1];
    const double ex0 = EXTENT_0 * (1.0 - fabs(oe0)), ex1 = EXTENT_1;
    low[k][0] = mid0 - ex0; low[k][1] = mid1 - ex1;
    high[k][0] = mid0 + ex0; high[k][1] = mid1 + ex1;
  }
}

static void c_into(const double zmp[2], const double xi[2], const double lo[2], const double hi[2],
                   double om, double share, double out[2]) {
  for (int d = 0; d < 2; d++) {
    const double plain = c_clip(zmp[d], lo[d], hi[d]);
    const double v0 = c_clip(zmp[d], xi[d] - (hi[d] - xi[d]) / (om * CAPTURE_S),
                             xi[d] + (xi[d] - lo[d]) / (om * CAPTURE_S));
    out[d] = plain + share * (c_clip(v0, lo[d], hi[d]) - plain);
  }
}

static void c_reading(const double *y, const double *fr, const double stood[2],
                      double z[11], double zd[11], double leg0[2][3], double leg1[2],
                      double leg2[2], double turn[3][2], double spun[3][2]) {
  double place[2][3], speed[2][3];
  for (int k = 0; k < 2; k++) {
    const double ds[3] = {y[6 + 3 * k] - y[0], y[7 + 3 * k] - y[1], y[8 + 3 * k] - y[2]};
    const double dv[3] = {y[12 + 3 * k] - y[3], y[13 + 3 * k] - y[4], y[14 + 3 * k] - y[5]};
    const double hs[3] = {y[39 + 3 * k] - y[6 + 3 * k], y[40 + 3 * k] - y[7 + 3 * k], y[41 + 3 * k] - y[8 + 3 * k]};
    const double vs[3] = {y[3] - y[12 + 3 * k], y[4] - y[13 + 3 * k], y[5] - y[14 + 3 * k]};
    const double tk = y[45 + k], st = sin(tk), ct = cos(tk);
    const double spoke[3] = {st, 0.0, ct}, inward[3] = {ct, 0.0, -st};
    for (int r = 0; r < 3; r++) {
      place[k][r] = dot3(ds, fr + 3 * r);
      speed[k][r] = dot3(dv, fr + 3 * r);
      leg0[k][r] = dot3(hs, fr + 3 * r) - ANKLE_H * spoke[r] + MIDDLE * inward[r];
    }
    leg1[k] = sqrt(dot3(leg0[k], leg0[k]));
    leg2[k] = (dot3(vs, fr + 0) * leg0[k][0] + dot3(vs, fr + 3) * leg0[k][1] + dot3(vs, fr + 6) * leg0[k][2]) / leg1[k];
    const double w = y[20 + 4 * k], x = y[21 + 4 * k], j = y[22 + 4 * k], qk = y[23 + 4 * k];
    const double left[3] = {1.0 - 2.0 * (j * j + qk * qk), 2.0 * (x * j + w * qk), 2.0 * (x * qk - w * j)};
    const double up_v[3] = {2.0 * (x * j - w * qk), 1.0 - 2.0 * (x * x + qk * qk), 2.0 * (j * qk + w * x)};
    const double on_v[3] = {2.0 * (x * qk + w * j), 2.0 * (j * qk - w * x), 1.0 - 2.0 * (x * x + j * j)};
    const double *sp = y + 28 + 3 * k;
    turn[0][k] = atan2(dot3(up_v, fr + 0), up_v[1]);
    turn[1][k] = atan2(left[1], dot3(left, fr + 3));
    turn[2][k] = atan2(dot3(on_v, fr + 3), dot3(on_v, fr + 0));
    spun[0][k] = dot3(sp, fr + 3); spun[1][k] = dot3(sp, fr + 0); spun[2][k] = dot3(sp, fr + 6);
  }
  const double w0 = (stood[0] + TINY) / (stood[0] + stood[1] + 2.0 * TINY);
  const double w1 = (stood[1] + TINY) / (stood[0] + stood[1] + 2.0 * TINY);
  for (int n = 0; n < 11; n++) {
    double zn = 0.0, zdn = 0.0;
    for (int i = 0; i < 2; i++) {
      for (int r = 0; r < 3; r++) {
        zn += C_HANDS[(n * 2 + i) * 3 + r] * place[i][r];
        zdn += C_HANDS[(n * 2 + i) * 3 + r] * speed[i][r];
      }
    }
    z[n] = 0.5 * zn / fr[23 + n] + fr[34 + n];
    zd[n] = 0.5 * zdn / fr[23 + n];
  }
  z[AXIAL] = (fr[19] - (w0 * leg1[0] + w1 * leg1[1])) / (AXIAL_M * fr[20]);
  zd[AXIAL] = -(w0 * leg2[0] + w1 * leg2[1]) / (AXIAL_M * fr[20]);
  z[PITCH] += (turn[0][1] - fr[16]) / fr[23 + PITCH]; zd[PITCH] += spun[0][1] / fr[23 + PITCH];
  z[LIST] += turn[1][0] / fr[23 + LIST]; zd[LIST] += spun[1][0] / fr[23 + LIST];
  z[TURN] += turn[2][0] / fr[23 + TURN]; zd[TURN] += spun[2][0] / fr[23 + TURN];
  z[ROCK] += 0.5 * (y[45] - y[46]) / fr[23 + ROCK]; zd[ROCK] += 0.5 * (y[47] - y[48]) / fr[23 + ROCK];
  z[ARMS] += 0.5 * ((y[49] - fr[21]) - (y[50] - fr[22])) / fr[23 + ARMS];
}
'''


@functools.lru_cache(maxsize=None)
def transpile_law():
    """Verify the control modules' ASTs, emit `build/hosttest/law_core_*.c`, and return its path."""
    from tools.cores.manifest import c_impedance_ask
    os.makedirs(OUT, exist_ok=True)
    digest = _ast_verified()
    c_path = os.path.join(OUT, 'law_core_%s.c' % digest)
    if not os.path.exists(c_path):
        written(c_path, _c_header() + _c_latent_support() + _c_poise_stride()
                + c_swings_poses() + c_impedance_ask() + c_wrench_rounds())
    return c_path


@functools.lru_cache(maxsize=None)
def law_library():
    """The compiled C law core (`law_latent_step`, `law_support_couple`, `law_impedance_ask`, `law_wrench_rounds`)."""
    c_path = transpile_law()
    lib_path, _ = cached([c_path], [], 'law_core', ('-O2',))
    lib = ctypes.CDLL(lib_path)
    dp = ctypes.POINTER(ctypes.c_double)
    lib.law_latent_step.argtypes = [dp, dp, ctypes.c_int, ctypes.c_double, ctypes.c_double, dp]
    lib.law_latent_step.restype = None
    lib.law_support_couple.argtypes = [dp, dp, dp, dp, dp, dp, dp]
    lib.law_support_couple.restype = None
    lib.law_impedance_ask.argtypes = [dp, dp, dp, dp]
    lib.law_impedance_ask.restype = None
    lib.law_wrench_rounds.argtypes = [dp, dp, ctypes.c_double, ctypes.c_double,
                                      dp, dp, dp, ctypes.c_double, ctypes.c_double,
                                      dp, dp, dp, dp, dp, ctypes.c_double, dp, dp]
    lib.law_wrench_rounds.restype = None
    return lib


def wrench_rounds_c(H0, g0, lo, hi, geo, stride):
    """Run `wrench._rounds` in C (`law_wrench_rounds`) for the 21-unknown contact-free case."""
    import numpy as np
    _nu, _k3, _moment, part, up, lift, mass, grounded, stance, frames, edges, mu = geo
    strides, kinetic = stride
    dp = ctypes.POINTER(ctypes.c_double)
    ptr = lambda a: np.ascontiguousarray(a, dtype=np.float64).ctypes.data_as(dp)
    out = np.empty(21, dtype=np.float64)
    kc = kinetic if kinetic is not None else H0
    law_library().law_wrench_rounds(ptr(H0), ptr(g0), float(lo), float(hi), ptr(part), ptr(up), ptr(lift),
                                    float(mass), float(grounded), ptr(stance), ptr(frames[0]), ptr(frames[1]),
                                    ptr(edges), ptr(mu), float(strides), ptr(kc), out.ctypes.data_as(dp))
    return out
